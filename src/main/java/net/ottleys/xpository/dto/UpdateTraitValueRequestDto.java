package net.ottleys.xpository.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;

/**
 * Request DTO for updating a trait value on an element.
 *
 * <p>Validates that a new value is provided.
 */
@Schema(description = "Request to update a trait value")
public class UpdateTraitValueRequestDto {

  @NotBlank(message = "Trait value is required")
  @Schema(description = "New value for the trait", example = "Secret")
  private String value;

  /** Default constructor. */
  public UpdateTraitValueRequestDto() {}

  /**
   * Returns the value.
   *
   * @return the value
   */
  public String getValue() {
    return value;
  }

  /**
   * Sets the value.
   *
   * @param value the value
   */
  public void setValue(String value) {
    this.value = value;
  }
}
